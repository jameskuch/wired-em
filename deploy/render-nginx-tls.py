#!/usr/bin/env python3
"""Regenerate deploy/nginx-sbfsem-tls.conf from deploy/nginx-sbfsem.conf.

The two configs share their proxy, gzip and caching rules.  Keeping the TLS
one hand-edited guarantees they drift, and a drifted proxy timeout is the kind
of thing that only shows up as an unexplained 504 months later.  Run this after
changing the HTTP config::

    python3 deploy/render-nginx-tls.py
"""

from __future__ import annotations

import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
DOMAIN = "sbfsem-tools.com"

HEADER = f"""# nginx reverse proxy for SBFSEM-pytools, with TLS.
#
# GENERATED by deploy/render-nginx-tls.py -- edit nginx-sbfsem.conf instead.
#
# Installed by deploy/bootstrap.sh INSTEAD OF nginx-sbfsem.conf once a
# Let's Encrypt certificate exists for the domain.  Get one with:
#
#   sudo bash /srv/sbfsem/app/deploy/certbot-setup.sh {DOMAIN} you@example.com

upstream sbfsem_app {{
    server 127.0.0.1:8765;
    keepalive 8;
}}

# Port 80 does two jobs: serve ACME renewals, and send everything else to HTTPS.
server {{
    listen 80;
    listen [::]:80;
    server_name {DOMAIN} www.{DOMAIN} _;

    location ^~ /.well-known/acme-challenge/ {{
        root /var/www/certbot;
        default_type "text/plain";
        access_log off;
    }}

    # To the canonical name, not $host: a visitor arriving on the bare IP
    # would otherwise be sent to https://<ip>, where the certificate cannot
    # match and the browser shows a warning before anything loads.
    location / {{
        return 301 https://{DOMAIN}$request_uri;
    }}
}}

server {{
    # `listen ... http2` rather than the newer `http2 on;` directive: Ubuntu
    # 24.04 ships nginx 1.24, where `http2 on` is an unknown directive and the
    # config will not load at all.  The old form works on both, warning only.
    listen 443 ssl http2;
    listen [::]:443 ssl http2;
    server_name {DOMAIN} www.{DOMAIN};

    ssl_certificate     /etc/letsencrypt/live/{DOMAIN}/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/{DOMAIN}/privkey.pem;
    ssl_trusted_certificate /etc/letsencrypt/live/{DOMAIN}/chain.pem;

    # Mozilla "intermediate": TLS 1.2+ only, no legacy ciphers.
    ssl_protocols TLSv1.2 TLSv1.3;
    ssl_prefer_server_ciphers off;
    ssl_session_cache shared:SbfsemTLS:10m;
    ssl_session_timeout 1d;
    ssl_session_tickets off;
    # No ssl_stapling: Let's Encrypt has stopped issuing certificates with an
    # OCSP responder URL, so it is a no-op that warns on every `nginx -t`.

    # Deliberately short to start with. A long max-age is hard to undo -- every
    # browser that has seen it refuses plain HTTP for that long, even if the
    # certificate lapses. Raise it to 31536000 once renewal has run cleanly.
    add_header Strict-Transport-Security "max-age=86400" always;
    add_header X-Content-Type-Options "nosniff" always;
    add_header Referrer-Policy "same-origin" always;

"""

FOOTER = f"""}}

# The bare IP still answers on 443, but no certificate can be valid for it, so
# refuse rather than serving the site under a name it does not match.
server {{
    listen 443 ssl default_server;
    listen [::]:443 ssl default_server;
    server_name _;
    ssl_certificate     /etc/letsencrypt/live/{DOMAIN}/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/{DOMAIN}/privkey.pem;
    return 301 https://{DOMAIN}$request_uri;
}}
"""


def main() -> int:
    src = (HERE / "nginx-sbfsem.conf").read_text()
    marker = "    # A neuron's mesh JSON is float text"
    if marker not in src:
        print("anchor missing from nginx-sbfsem.conf -- refusing to guess", file=sys.stderr)
        return 1
    body = src[src.index(marker):src.rindex("}")].rstrip() + "\n"
    (HERE / "nginx-sbfsem-tls.conf").write_text(HEADER + body + FOOTER)
    print("wrote", HERE / "nginx-sbfsem-tls.conf")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
