def test_trim_memory_is_safe_everywhere():
    """glibc-only, but must never raise on any platform."""
    import platform

    from sbfsem.util.memory import malloc_trim_available, trim_memory

    available = malloc_trim_available()
    assert isinstance(available, bool)
    assert available is (platform.system() == "Linux" and available)
    # Returns a bool and does not raise, whether or not it did anything.
    assert isinstance(trim_memory(), bool)
    assert isinstance(trim_memory(collect=False), bool)
    if platform.system() != "Linux":
        assert available is False
        assert trim_memory() is False
