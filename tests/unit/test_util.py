def test_update_offsets_applies_each_section_once():
    """F216: MATLAB's ranges overlapped at min(sections), doubling that row."""
    base = read_xy_offset("i")
    result = RegistrationResult(
        offsets=np.array([[100.0, 1.0, 2.0], [101.0, 1.5, 2.5]]),
        stats=pd.DataFrame(), neuron_ids=np.array([1]), columns=("VolumeX", "VolumeY"),
    )
    table = update_offsets("i", result)
    row = {int(s): i for i, s in enumerate(table[:, 0])}
    assert table[row[100], 1] == pytest.approx(base[row[100], 1] + 1.0)
    assert table[row[101], 1] == pytest.approx(base[row[101], 1] + 1.5)
    # Sections below the lowest measured one inherit its offset, exactly once.
    assert table[row[99], 1] == pytest.approx(base[row[99], 1] + 1.0)
    assert table[row[1], 1] == pytest.approx(base[row[1], 1] + 1.0)
    # Sections above are untouched.
    assert table[row[102], 1] == pytest.approx(base[row[102], 1])


def test_update_offsets_skips_unknown_sections():
    result = RegistrationResult(
        offsets=np.array([[10.0, 1.0, 1.0], [999999.0, 5.0, 5.0]]),
        stats=pd.DataFrame(), neuron_ids=np.array([1]), columns=("VolumeX", "VolumeY"),
    )
    table = update_offsets("i", result)
    assert np.isfinite(table).all()


def test_write_offset_file(tmp_path):
    table = np.array([[1.0, 2.0, 3.0], [2.0, 4.0, 5.0]])
    path = write_offset_file("i", table, tmp_path / "XY_OFFSET_TEST.txt")
    np.testing.assert_allclose(np.loadtxt(path, delimiter=","), table)


def test_xy_shift_bridges_a_gap(c943):
    sections = sorted(c943.get_cell_nodes()["Z"].unique())
    x, y, offset = xy_shift(c943, (sections[0], sections[1]))
    assert x.shape == y.shape == (len(c943.nodes),)
    assert offset.shape == (2,)


def test_xy_shift_with_no_bridging_annotations(c943):
    x, y, offset = xy_shift(c943, (999998, 999999))
    np.testing.assert_array_equal(offset, [0, 0])
    np.testing.assert_allclose(x, c943.nodes["VolumeX"].to_numpy())


